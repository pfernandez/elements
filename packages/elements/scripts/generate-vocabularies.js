import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { htmlElements } from '../src/vocabularies/html.js'
import { svgElements } from '../src/vocabularies/svg.js'
import { mathmlElements } from '../src/vocabularies/mathml.js'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const srcDir = path.resolve(scriptDir, '../src')

const comment = ({ description, url }) => {
  const lines = [description, url].filter(Boolean)
    .flatMap(value => value.split('\n'))
  return ['/**', ...lines.map(line => ` * ${line}`), ' */'].join('\n')
}

const moduleSource = (label, items) =>
  [
    '// Generated by scripts/generate-vocabularies.js. Do not edit by hand.',
    `// Source: src/vocabularies/${label.toLowerCase()}.js`,
    '',
    "import { element } from './core/element.js'",
    '',
    ...items.flatMap(item => [
      comment(item),
      `export const ${item.name} = element(${JSON.stringify(item.tag)})`,
      ''
    ])
  ].join('\n')

const write = (name, items) =>
  fs.writeFileSync(path.join(srcDir, `${name}.js`), moduleSource(name, items))

const tagsSource = [
  '// Generated by scripts/generate-vocabularies.js. Do not edit by hand.',
  '',
  `export const htmlTagNames = /** @type {const} */ (${JSON.stringify(
    htmlElements.map(({ tag }) => tag), null, 2
  )})`,
  '',
  `export const svgTagNames = /** @type {const} */ (${JSON.stringify(
    svgElements.map(({ tag }) => tag), null, 2
  )})`,
  ''
].join('\n')

write('html', htmlElements)
write('svg', svgElements)
write('mathml', mathmlElements)
fs.writeFileSync(path.join(srcDir, 'core', 'tags.js'), tagsSource)
